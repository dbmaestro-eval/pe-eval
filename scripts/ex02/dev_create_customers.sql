CREATE TABLE dbo.EX_CUSTOMERS (
    CUSTOMER_ID   INT            NOT NULL,
    FIRST_NAME    NVARCHAR(50)   NOT NULL,
    LAST_NAME     NVARCHAR(50)   NOT NULL,
    EMAIL         NVARCHAR(100)  NULL,
    CREATED_AT    DATETIME2      NOT NULL CONSTRAINT DF_EX_CUSTOMERS_CREATED_AT DEFAULT (SYSDATETIME()),
    CONSTRAINT PK_EX_CUSTOMERS PRIMARY KEY (CUSTOMER_ID)
);
GO
